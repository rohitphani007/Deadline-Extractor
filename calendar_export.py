"""
Calendar export module — generates ICS calendar files from extracted
deadlines so students can import them into Google Calendar, Apple
Calendar, Outlook, etc.
"""

from datetime import datetime, timedelta
from pathlib import Path

from ics import Calendar, Event
from ics.alarm import DisplayAlarm


def create_calendar(deadlines: list[dict], reminder_minutes: int = 60) -> str:
    """
    Create an ICS calendar string from a list of deadline dicts.

    Each deadline becomes a calendar event with:
    - **Name**: ``[Subject] Task`` (or just ``Task`` if no subject)
    - **Start time**: the resolved deadline datetime
    - **Duration**: 1 hour (acts as a visible reminder block)
    - **Description**: original message + who posted it
    - **Alarm**: fires ``reminder_minutes`` before the event

    Parameters
    ----------
    deadlines : list[dict]
        Each dict should have at minimum ``task`` and ``resolved_date``.
        Optional keys: ``subject``, ``posted_by``, ``original_message``,
        ``urgency``.
    reminder_minutes : int
        How many minutes before the deadline to trigger a reminder
        (default 60).

    Returns
    -------
    str
        The full ICS calendar as a string.
    """
    cal = Calendar()

    for dl in deadlines:
        resolved = dl.get("resolved_date")
        if resolved is None:
            continue  # cannot create an event without a date

        task = dl.get("task", "Assignment deadline")
        subject = dl.get("subject", "")
        posted_by = dl.get("posted_by", "Unknown")
        original_msg = dl.get("original_message", "")
        urgency = dl.get("urgency", "")
        date_phrase = dl.get("date_phrase", "")

        # Event name
        if subject:
            event_name = f"[{subject}] {task}"
        else:
            event_name = task

        event = Event()
        event.name = event_name
        event.begin = resolved
        event.duration = timedelta(hours=1)

        # Build description
        desc_parts = [
            f"📌 Task: {task}",
        ]
        if subject:
            desc_parts.append(f"📚 Subject: {subject}")
        if urgency:
            desc_parts.append(f"⚡ Urgency: {urgency}")
        desc_parts.append(f"👤 Posted by: {posted_by}")
        if date_phrase:
            desc_parts.append(f"🗓  Original phrase: \"{date_phrase}\"")
        if original_msg:
            desc_parts.append(f"\n💬 Original message:\n{original_msg}")
        desc_parts.append(
            "\n— Generated by Deadline Extractor 🦥"
        )
        event.description = "\n".join(desc_parts)

        # Add alarm / reminder
        alarm = DisplayAlarm()
        alarm.trigger = timedelta(minutes=-reminder_minutes)
        alarm.display_text = f"⏰ Deadline coming up: {event_name}"
        if hasattr(event.alarms, "append"):
            event.alarms.append(alarm)
        elif hasattr(event.alarms, "add"):
            event.alarms.add(alarm)

        cal.events.add(event)

    if hasattr(cal, "serialize"):
        return cal.serialize()
    return str(cal)


def save_calendar(
    deadlines: list[dict],
    output_path: str = "deadlines.ics",
    reminder_minutes: int = 60,
) -> str:
    """
    Generate an ICS calendar from deadlines and save it to disk.

    Parameters
    ----------
    deadlines : list[dict]
        Deadline dicts (must include ``resolved_date``).
    output_path : str
        File path for the ``.ics`` output (default ``deadlines.ics``).
    reminder_minutes : int
        Minutes before each event to trigger a reminder.

    Returns
    -------
    str
        The absolute path of the saved file.
    """
    ics_content = create_calendar(deadlines, reminder_minutes=reminder_minutes)

    path = Path(output_path)
    path.write_text(ics_content, encoding="utf-8")

    return str(path.resolve())
